from contextlib import AbstractContextManager
from typing import Protocol

from agent_relay.application.transactions import RepositoryScope
from agent_relay.domain.rooms.models import Channel, Room, RoomState


class ChannelQueries(Protocol):
    def channels(self, room_id: str) -> list[Channel]: ...
    def channel(self, room_id: str, channel_id: str) -> Channel: ...


class ChannelData(ChannelQueries, Protocol):
    def room(self, room_id: str) -> Room: ...
    def insert(self, channel: Channel, state: RoomState) -> None: ...
    def delete(self, room_id: str, channel_id: str) -> None: ...


class ChannelStore(RepositoryScope[ChannelData], Protocol):
    def guard(self, room_id: str) -> AbstractContextManager[None]: ...


class WorktreeDriver(Protocol):
    def inspect(self, source: str) -> str: ...
    def available(self, source: str, path: str, branch: str) -> None: ...
    def create(self, source: str, path: str, branch: str, commit: str) -> None: ...
    def verify(self, source: str, path: str, branch: str, commit: str) -> None: ...
